package com.sengine.project.templates

import com.sengine.engine.core.*
import com.sengine.engine.ui.*
import com.sengine.project.Project

/**
 * Professional 3D Endless Runner Game Template
 *
 * Features:
 * - Third-person runner with 3 lanes
 * - Procedural obstacle generation
 * - Collectible coins in 3D space
 * - Power-up system (shield, magnet, multiplier)
 * - Dynamic camera with smooth follow
 * - Professional 3D environment with lighting
 * - Particle effects and trails
 * - Score and distance tracking
 * - Professional 3D HUD
 * - Speed increase over time
 */
object Runner3DTemplate {
    const val NAME = "3D Endless Runner"
    const val DESC = "Professional 3D endless runner with lane-switching, procedural obstacles, power-ups, dynamic camera, particles, professional HUD and speed progression."

    fun create(project: Project) {
        writeScripts(project)

        val scene = Scene("Main")
        scene.gravityY = -20f
        scene.fog = true
        scene.fogColor = 0xFF87CEEB.toInt()
        scene.fogStart = 30f
        scene.fogEnd = 120f
        scene.ambient = 0xFF607080.toInt()

        // ── Main Camera (3D) ──
        val cam = scene.create("MainCamera")
        cam.add(Camera3D().also {
            it.fov = 60f; it.nearClip = 0.1f; it.farClip = 200f
            it.clearColor = 0xFF87CEEB.toInt()
        })
        cam.y = 5f; cam.z = -8f; cam.rotX = -15f
        cam.add(ScriptComponent().also {
            it.script = "RunnerCamera.js"
            it.params = "followTarget=Player, offsetY=5, offsetZ=-8, smoothTime=0.15"
        })

        // ── Lighting ──
        val sun = scene.create("DirectionalLight")
        sun.add(Light().also {
            it.kind = 0; it.intensity = 1.0f; it.color = 0xFFFFF8E7.toInt()
        })
        sun.rotX = -45f; sun.rotation = 30f

        val fillLight = scene.create("FillLight")
        fillLight.add(Light().also {
            it.kind = 1; it.intensity = 0.5f; it.color = 0xFFB0C4DE.toInt()
            it.range = 30f
        })
        fillLight.x = -5f; fillLight.y = 3f; fillLight.z = 5f

        // ── Player ──
        val player = scene.create("Player")
        player.tag = "Player"
        player.add(MeshRenderer().also {
            it.mesh = 1 // Capsule
            it.color = 0xFF4488FF.toInt()
        })
        player.scaleX = 0.8f; player.scaleY = 1.5f; player.scaleZ = 0.8f
        player.y = 1f
        player.add(Rigidbody3D().also {
            it.mass = 1f; it.gravityScale = 2.5f; it.freezeRotation = true
        })
        player.add(Collider3D().also {
            it.shape = 1; it.radius = 0.5f; it.height = 1.8f
        })
        player.add(ScriptComponent().also {
            it.script = "RunnerController.js"
            it.params = "laneSpeed=12, jumpForce=12, slideTime=0.6, lanes=-3,0,3"
        })

        // ── Ground ──
        val ground = scene.create("Ground")
        ground.tag = "Ground"
        ground.scaleX = 12f; ground.scaleY = 0.5f; ground.scaleZ = 200f
        ground.z = 80f
        ground.add(MeshRenderer().also {
            it.mesh = 0; it.color = 0xFF3A5F3A.toInt()
        })
        ground.add(Rigidbody3D().also { it.bodyType = 2 })
        ground.add(Collider3D().also { it.shape = 0; it.width = 1f; it.height = 1f; it.depth = 1f })

        // ── Lane Markers ──
        for (i in -1..1) {
            val lane = scene.create("LaneMarker_$i")
            lane.x = i.toFloat() * 3f; lane.y = 0.3f; lane.z = 50f
            lane.scaleX = 0.1f; lane.scaleY = 0.05f; lane.scaleZ = 100f
            lane.add(MeshRenderer().also {
                it.mesh = 0; it.color = 0x40FFFFFF.toInt()
            })
        }

        // ── Side Walls ──
        for (side in listOf(-1, 1)) {
            val wall = scene.create("Wall_$side")
            wall.x = side.toFloat() * 7f; wall.y = 3f; wall.z = 50f
            wall.scaleX = 0.5f; wall.scaleY = 6f; wall.scaleZ = 100f
            wall.add(MeshRenderer().also {
                it.mesh = 0; it.color = 0xFF2C3E50.toInt()
            })
        }

        // ── Obstacles (pre-placed, more generated by script) ──
        val obstacleData = listOf(
            floatArrayOf(0f, 1f, 15f, 0f),  // x, y, z, type (0=box, 1=low, 2=wide)
            floatArrayOf(-3f, 1f, 25f, 0f),
            floatArrayOf(3f, 0.5f, 35f, 1f),
            floatArrayOf(0f, 1f, 45f, 2f),
            floatArrayOf(-3f, 1f, 55f, 0f),
            floatArrayOf(3f, 1f, 65f, 0f),
            floatArrayOf(0f, 0.5f, 75f, 1f),
        )
        for ((i, d) in obstacleData.withIndex()) {
            val obs = scene.create("Obstacle_$i")
            obs.tag = "Obstacle"
            obs.x = d[0]; obs.y = d[1]; obs.z = d[2]
            val otype = d[3].toInt()
            when (otype) {
                0 -> { obs.scaleX = 1.5f; obs.scaleY = 2f; obs.scaleZ = 1f }
                1 -> { obs.scaleX = 3f; obs.scaleY = 0.8f; obs.scaleZ = 1f }
                2 -> { obs.scaleX = 5f; obs.scaleY = 2f; obs.scaleZ = 0.5f }
            }
            obs.add(MeshRenderer().also {
                it.mesh = 0; it.color = 0xFFE74C3C.toInt()
            })
            obs.add(Collider3D().also {
                it.shape = 0; it.width = 1f; it.height = 1f; it.depth = 1f; it.isTrigger = true
            })
            obs.add(ScriptComponent().also {
                it.script = "Obstacle.js"
            })
        }

        // ── Coins ──
        val coinPositions = listOf(
            floatArrayOf(0f, 1.5f, 10f), floatArrayOf(0f, 1.5f, 12f), floatArrayOf(0f, 1.5f, 14f),
            floatArrayOf(-3f, 1.5f, 20f), floatArrayOf(-3f, 1.5f, 22f),
            floatArrayOf(3f, 1.5f, 30f), floatArrayOf(3f, 1.5f, 32f), floatArrayOf(3f, 1.5f, 34f),
            floatArrayOf(0f, 3f, 40f), floatArrayOf(0f, 3f, 42f),
            floatArrayOf(-3f, 1.5f, 50f), floatArrayOf(0f, 1.5f, 52f), floatArrayOf(3f, 1.5f, 54f),
            floatArrayOf(0f, 1.5f, 60f), floatArrayOf(0f, 1.5f, 62f), floatArrayOf(0f, 1.5f, 64f),
            floatArrayOf(-3f, 1.5f, 70f), floatArrayOf(3f, 1.5f, 72f),
        )
        for ((i, p) in coinPositions.withIndex()) {
            val coin = scene.create("Coin_$i")
            coin.tag = "Coin"
            coin.x = p[0]; coin.y = p[1]; coin.z = p[2]
            coin.scaleX = 0.5f; coin.scaleY = 0.5f; coin.scaleZ = 0.5f
            coin.add(MeshRenderer().also {
                it.mesh = 1; it.color = 0xFFFFD700.toInt()
            })
            coin.add(Collider3D().also {
                it.shape = 1; it.radius = 0.5f; it.isTrigger = true
            })
            coin.add(ScriptComponent().also {
                it.script = "Coin3D.js"
            })
        }

        // ── Power-ups ──
        val powerupData = listOf(
            floatArrayOf(-3f, 1.5f, 40f, 0f), // Shield
            floatArrayOf(3f, 1.5f, 60f, 1f),  // Magnet
            floatArrayOf(0f, 1.5f, 80f, 2f),  // Multiplier
        )
        for ((i, d) in powerupData.withIndex()) {
            val pu = scene.create("PowerUp_$i")
            pu.tag = "PowerUp"
            pu.x = d[0]; pu.y = d[1]; pu.z = d[2]
            pu.scaleX = 0.7f; pu.scaleY = 0.7f; pu.scaleZ = 0.7f
            val puType = d[3].toInt()
            pu.add(MeshRenderer().also {
                it.mesh = 2 // Sphere
                it.color = when (puType) {
                    0 -> 0xFF00BFFF.toInt() // Shield - blue
                    1 -> 0xFFFF69B4.toInt() // Magnet - pink
                    else -> 0xFFADFF2F.toInt() // Multiplier - green
                }
            })
            pu.add(Collider3D().also {
                it.shape = 1; it.radius = 0.7f; it.isTrigger = true
            })
            pu.add(ScriptComponent().also {
                it.script = "PowerUp3D.js"
                it.params = "type=${puType}"
            })
        }

        // ── Player Trail Particles ──
        val trail = scene.create("PlayerTrail")
        trail.add(ParticleEmitter().also {
            it.emitting = true; it.rate = 30f
            it.startColor = 0x804488FF.toInt(); it.endColor = 0x004488FF.toInt()
            it.startSize = 0.3f; it.endSize = 0f; it.lifetime = 0.5f
            it.speed = 0.5f; it.gravity = 0f
        })
        trail.add(ScriptComponent().also {
            it.script = "TrailFollow.js"
            it.params = "target=Player"
        })

        // ── Environment Decorations ──
        for (i in 0 until 20) {
            for (side in listOf(-1, 1)) {
                val tree = scene.create("Tree_${side}_${i}")
                tree.x = side.toFloat() * (9f + (i % 3) * 2f)
                tree.y = 2f
                tree.z = i.toFloat() * 10f + 5f
                tree.scaleX = 1.5f; tree.scaleY = 4f; tree.scaleZ = 1.5f
                tree.add(MeshRenderer().also {
                    it.mesh = 1; it.color = 0xFF2E7D32.toInt()
                })
            }
        }

        // ── HUD ──
        val hudCanvas = scene.create("HUD_Canvas")
        hudCanvas.add(UICanvas().also { it.refWidth = 1920; it.refHeight = 1080; it.scaleMode = 3; it.sortOrder = 100 })

        // Score
        val scoreText = scene.create("HUD_Score")
        scoreText.tag = "ScoreText"
        scoreText.parent = hudCanvas
        scoreText.add(RectTransform().also {
            it.anchorMinX = 0.5f; it.anchorMinY = 1f; it.anchorMaxX = 0.5f; it.anchorMaxY = 1f
            it.anchoredY = -30f; it.width = 400f; it.height = 60f
        })
        scoreText.add(UIText().also { it.text = "0"; it.fontSize = 48; it.color = 0xFFFFFFFF.toInt(); it.bold = true })

        // Distance
        val distText = scene.create("HUD_Distance")
        distText.tag = "DistanceText"
        distText.parent = hudCanvas
        distText.add(RectTransform().also {
            it.anchorMinX = 1f; it.anchorMinY = 1f; it.anchorMaxX = 1f; it.anchorMaxY = 1f
            it.pivotX = 1f; it.pivotY = 1f
            it.anchoredX = -20f; it.anchoredY = -20f; it.width = 300f; it.height = 40f
        })
        distText.add(UIText().also { it.text = "0m"; it.fontSize = 32; it.color = 0xFFCCCCCC.toInt() })

        // Coin counter
        val coinHud = scene.create("HUD_Coins")
        coinHud.tag = "CoinCounter"
        coinHud.parent = hudCanvas
        coinHud.add(RectTransform().also {
            it.anchorMinX = 0f; it.anchorMinY = 1f; it.anchorMaxX = 0f; it.anchorMaxY = 1f
            it.pivotX = 0f; it.pivotY = 1f
            it.anchoredX = 20f; it.anchoredY = -20f; it.width = 200f; it.height = 40f
        })
        coinHud.add(UIText().also { it.text = "× 0"; it.fontSize = 36; it.color = 0xFFFFD700.toInt(); it.bold = true })

        // Game Manager
        val gm = scene.create("GameManager")
        gm.add(ScriptComponent().also {
            it.script = "RunnerGameManager.js"
            it.params = "baseSpeed=12, maxSpeed=35, speedIncrease=0.1"
        })
    }

    private fun writeScripts(project: Project) {
        // Runner Controller
        project.assetFile("RunnerController.js").writeText("""
// RunnerController.js — 3D Runner Character Controller
// Params: laneSpeed=12, jumpForce=12, slideTime=0.6, lanes=-3,0,3
var currentLane = 1; // 0=left, 1=center, 2=right
var targetX = 0;
var isGrounded = true;
var isSliding = false;
var slideTimer = 0;
var laneArray = [-3, 0, 3];
var shieldActive = false;
var shieldTimer = 0;
var magnetActive = false;
var magnetTimer = 0;
var multiplierActive = false;
var multiplierTimer = 0;

function start() {
    currentLane = 1;
    targetX = 0;
}

function update(dt) {
    // Lane switching
    if (input.aDown && currentLane > 0) {
        currentLane--;
        targetX = laneArray[currentLane];
    }
    if (input.bDown && currentLane < 2) {
        currentLane++;
        targetX = laneArray[currentLane];
    }

    // Smooth lane transition
    var dx = targetX - self.x;
    self.x += dx * laneSpeed * dt;

    // Jump
    if (input.aDown && isGrounded) {
        self.vy = jumpForce;
        isGrounded = false;
    }

    // Slide
    if (isSliding) {
        slideTimer -= dt;
        self.scaleY = 0.5;
        if (slideTimer <= 0) {
            isSliding = false;
            self.scaleY = 1.5;
        }
    }

    // Gravity / ground check handled by physics

    // Power-up timers
    if (shieldActive) { shieldTimer -= dt; if (shieldTimer <= 0) shieldActive = false; }
    if (magnetActive) { magnetTimer -= dt; if (magnetTimer <= 0) magnetActive = false; }
    if (multiplierActive) { multiplierTimer -= dt; if (multiplierTimer <= 0) multiplierActive = false; }

    // Death by falling
    if (self.y < -5) {
        scene.reload();
    }
}

function onCollision(other) {
    if (other.tag == "Ground") {
        isGrounded = true;
    }
}

function onTrigger(other) {
    if (other.tag == "Obstacle" && !shieldActive) {
        scene.reload();
    }
}

function activateShield(duration) {
    shieldActive = true;
    shieldTimer = duration;
}

function activateMagnet(duration) {
    magnetActive = true;
    magnetTimer = duration;
}

function activateMultiplier(duration) {
    multiplierActive = true;
    multiplierTimer = duration;
}
        """.trimIndent())

        // Runner Camera
        project.assetFile("RunnerCamera.js").writeText("""
// RunnerCamera.js — Smooth follow camera for 3D runner
var target = null;
var velocity = [0, 0, 0];

function start() {
    target = scene.find("Player");
}

function update(dt) {
    if (!target) return;
    var desiredX = target.x;
    var desiredY = target.y + 5;
    var desiredZ = target.z - 8;

    // Smooth follow
    self.x += (desiredX - self.x) * 5 * dt;
    self.y += (desiredY - self.y) * 3 * dt;
    self.z += (desiredZ - self.z) * 5 * dt;

    // Look at player
    var dx = target.x - self.x;
    var dy = target.y - self.y;
    var dz = target.z - self.z;
    self.rotX = -15;
}
        """.trimIndent())

        // Obstacle
        project.assetFile("Obstacle.js").writeText("""
// Obstacle.js — 3D Runner obstacle
function onTrigger(other) {
    if (other.tag == "Player") {
        other.send("hit");
    }
}
        """.trimIndent())

        // Coin 3D
        project.assetFile("Coin3D.js").writeText("""
// Coin3D.js — 3D runner coin collectible
var time = 0;
var collected = false;

function update(dt) {
    time += dt;
    self.rotation = time * 180;
    self.y += sin(time * 3) * 0.002;
}

function onTrigger(other) {
    if (collected) return;
    if (other.tag == "Player") {
        collected = true;
        audio.beep();
        self.destroy();
    }
}
        """.trimIndent())

        // Power-up 3D
        project.assetFile("PowerUp3D.js").writeText("""
// PowerUp3D.js — 3D runner power-up
// type: 0=shield, 1=magnet, 2=multiplier
var time = 0;
var collected = false;

function update(dt) {
    time += dt;
    self.rotation = time * 90;
    self.y = 1.5 + sin(time * 2) * 0.3;
}

function onTrigger(other) {
    if (collected || other.tag != "Player") return;
    collected = true;
    audio.beep();
    other.send("powerup", type);
    self.destroy();
}
        """.trimIndent())

        // Trail Follow
        project.assetFile("TrailFollow.js").writeText("""
// TrailFollow.js — Follow target for particle effects
function update(dt) {
    var t = scene.find("Player");
    if (t) {
        self.x = t.x;
        self.y = t.y - 0.5;
        self.z = t.z;
    }
}
        """.trimIndent())

        // Runner Game Manager
        project.assetFile("RunnerGameManager.js").writeText("""
// RunnerGameManager.js — 3D Runner game state
var score = 0;
var distance = 0;
var coins = 0;
var speed = 12;
var time = 0;

function start() {
    score = 0;
    distance = 0;
    coins = 0;
    speed = 12;
}

function update(dt) {
    time += dt;
    distance += speed * dt;
    score = distance.toInt();

    // Gradually increase speed
    if (speed < 35) {
        speed += 0.1 * dt;
    }

    // Update HUD
    var scoreText = scene.find("ScoreText");
    if (scoreText) scoreText.text = "" + score;
    var distText = scene.find("DistanceText");
    if (distText) distText.text = distance.toInt() + "m";
    var coinText = scene.find("CoinCounter");
    if (coinText) coinText.text = "× " + coins;
}
        """.trimIndent())
    }
}
